Record slt_case : Type :=
  mk_slt_case_rec
    {
      slc_id : string;
      (** the types of the columns: [I], [R] or [T] *)
      slc_types : string;
      (** 0: [nosort], 1: [rowsort], 2: [valuesort] *)
      slc_sort : nat;
      slc_query : squery;
      (** the values, row by row *)
      slc_expected : list string;
      slc_sql : string
    }.

Definition mk_slt_case id types sort q expected sql := mk_slt_case_rec id types sort q expected sql.

(** A phase: the state of the tables, and the queries which are run in it. *)
Definition slt_phase := (list table_spec * list slt_case)%type.

(** * The text of the values, as sqllogictest writes them *)

(** [%.3f] *)
Definition fixed3 (q : Qc) : string :=
  let scaled := NullValues.Qc_round (Qcmult q (NullValues.Qc_of_Z 1000)) in
  let a := Z.abs scaled in
  (if Z.ltb scaled 0 then "-" else "") ++ NullValues.string_of_Z (Z.div a 1000) ++ "." ++ pad_zeros 3 (NullValues.string_of_Z (Z.modulo a 1000)).

(** the integer which a value converts to (truncation, as the conversion of a number to an integer) *)
Definition int_of_value (v : NullValues.value) : option Z :=
  match lenient v with
  | Some (NullValues.Num_Z z) => Some z
  | Some (NullValues.Num_Q q) => Some (NullValues.Qc_trunc q)
  | None => None
  end.

Definition printable (c : ascii) : ascii :=
  let n := nat_of_ascii c in if (Nat.ltb n 32 || Nat.ltb 126 n)%bool then "@"%char else c.

Definition render (ty : ascii) (v : NullValues.value) : string :=
  if NullValues.is_err v then "ERROR"
  else if NullValues.is_null v then "NULL"
  else match ty with
       | "I"%char => match int_of_value v with Some z => NullValues.string_of_Z z | None => "NULL" end
       | "R"%char => match lenient v with
                     | Some n => fixed3 (NullValues.Qc_of_num n)
                     | None => "NULL" end
       | _ => match text_of v with
              | Some "" => "(empty)"
              | Some s => NullValues.string_map printable s
              | None => "NULL"
              end
       end.

Fixpoint render_row (tys : string) (r : list NullValues.value) : list string :=
  match tys, r with
  | String t tys, v :: r => render t v :: render_row tys r
  | _, _ => nil
  end.

(** * Comparison *)

Fixpoint insert_str (x : string) (l : list string) : list string :=
  match l with
  | nil => x :: nil
  | y :: l' => match string_compare x y with Gt => y :: insert_str x l' | _ => x :: l end
  end.

Definition sort_strings (l : list string) : list string := fold_right insert_str nil l.

Fixpoint chunk (n : nat) (fuel : nat) (l : list string) : list (list string) :=
  match fuel, l with
  | O, _ | _, nil => nil
  | S f, _ => firstn n l :: chunk n f (skipn n l)
  end.

Definition list_string_eqb (a b : list string) : bool :=
  Nat.eqb (List.length a) (List.length b) && forallb (fun p => String.eqb (fst p) (snd p)) (combine a b).

Fixpoint remove_row_s (r : list string) (l : list (list string)) : option (list (list string)) :=
  match l with
  | nil => None
  | x :: l => if list_string_eqb r x then Some l
              else match remove_row_s r l with Some l' => Some (x :: l') | None => None end
  end.

Fixpoint rows_perm_s (a b : list (list string)) : bool :=
  match a with
  | nil => match b with nil => true | _ => false end
  | r :: a => match remove_row_s r b with Some b' => rows_perm_s a b' | None => false end
  end.

Definition slt_actual (d : vsem) (tabs : list table_spec) (c : slt_case) : list (list string) :=
  let db := build_db tabs in
  let n := String.length (slc_types c) in
  map (fun t => render_row (slc_types c) (map (fun i => dot (TD d) t (out_attr i)) (seq 0 n)))
      (eval_query_list ORN (dialect_of d) (_basesort _ db) (_instance _ db) (to_dialect d (slc_query c))).

Definition slt_ok (d : vsem) (tabs : list table_spec) (c : slt_case) : bool :=
  let n := String.length (slc_types c) in
  let actual := slt_actual d tabs c in
  let expected := chunk n (List.length (slc_expected c)) (slc_expected c) in
  match slc_sort c with
  | 0%nat => list_string_eqb (List.concat actual) (List.concat expected)
  | 1%nat => rows_perm_s actual expected
  | _ => list_string_eqb (sort_strings (List.concat actual)) (sort_strings (List.concat expected))
  end.

Definition slt_failures (d : vsem) (ps : list slt_phase) : list string :=
  flat_map (fun p => map slc_id (filter (fun c => negb (slt_ok d (fst p) c)) (snd p))) ps.

Definition slt_diagnose (d : vsem) (ps : list slt_phase) : list string :=
  flat_map (fun p =>
              map (fun c => slc_id c ++ " | " ++ slc_sql c ++ " | expected "
                            ++ show_rows (chunk (String.length (slc_types c)) (List.length (slc_expected c)) (slc_expected c))
                            ++ " | got " ++ show_rows (slt_actual d (fst p) c))
                  (filter (fun c => negb (slt_ok d (fst p) c)) (snd p))) ps.
