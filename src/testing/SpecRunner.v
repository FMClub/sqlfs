Definition table_spec := (string * list (attribute TNull) * list (list NullValues.value))%type.

Record spec_case : Type :=
  mk_spec_case
    {
      sc_id : string;
      sc_ordered : bool;
      sc_tables : list table_spec;
      sc_query : squery;
      sc_expected : list (list string);
      sc_sql : string;
      (** [LIMIT n] without [ORDER BY]: any [n] rows of the result of [sc_query] (TODO 3.10) *)
      sc_limit : option nat;
      (** the engine rejects the query (an error): the model must reject it or fail on it (TODO 8.17) *)
      sc_error : bool
    }.

Definition mk_case id ordered tabs q expected sql := mk_spec_case id ordered tabs q expected sql None false.
Definition mk_case_limit id (n : nat) tabs q expected sql := mk_spec_case id false tabs q expected sql (Some n) false.
Definition mk_case_error id tabs q sql := mk_spec_case id false tabs q nil sql None true.

(** The database of a case *)
Definition build_db (tabs : list table_spec) : db_state :=
  fold_left
    (fun db t => match t with
                 | (name, atts, rows) => mk_insert (create_table db (Rel name) atts) (Rel name) atts rows
                 end)
    tabs init_db.

(** A value, and the text of a result: NULLs are the same; an integer or a rational is compared as a
    number; a decimal, whose text has the scale of the engine, and the other values are compared as
    texts. The leading spaces of the text of a number are ignored. *)
Definition cell_ok (v : NullValues.value) (s0 : string) : bool :=
  (* the leading spaces of a number are the padding of a psql column aligned on the right
     (pg2result.py, aligned_cells): no engine prints a number with them *)
  let s := match v with
           | NullValues.Value_Z _ | NullValues.Value_I _ | NullValues.Value_Q _ | NullValues.Value_D _
           | NullValues.Value_F _ => NullValues.string_ltrim s0
           | _ => s0
           end in
  if String.eqb s "NULL" then NullValues.is_null v
  else match v with
       | NullValues.Value_Z (Some z) => 
         match parse_number s with (n, true) => match num_cmp (NullValues.Num_Z z) n with Eq => true | _ => false end | _ => false end
       | NullValues.Value_I (Some (z, _)) => 
         match parse_number s with (n, true) => match num_cmp (NullValues.Num_Z z) n with Eq => true | _ => false end | _ => false end
       | NullValues.Value_Q (Some q) => 
         match parse_number s with (n, true) => match num_cmp (NullValues.Num_Q q) n with Eq => true | _ => false end | _ => false end
       (* a decimal is compared by its text: the engine prints its scale *)
       | NullValues.Value_D (Some (q, _, sc)) => String.eqb s (NullValues.dec_text q sc)
       (* a float is compared by its text, as the MySQL family prints it *)
       | NullValues.Value_F (Some _) => match text_of v with Some t => String.eqb s t | None => false end
       (* a boolean: [1]/[0] in the MySQL family, [t]/[f] in psql *)
       | NullValues.Value_bool (Some b) => if b then String.eqb s "1" || String.eqb s "t" else String.eqb s "0" || String.eqb s "f"
       | NullValues.Value_string (Some t) => String.eqb s t
       (* the dates, the intervals, the JSON documents and the collated strings: by their text *)
       | _ => match text_of v with Some t => String.eqb s t | None => false end
       end.

Fixpoint row_ok (r : list NullValues.value) (e : list string) : bool :=
  match r, e with
  | nil, nil => true
  | v :: r, s :: e => cell_ok v s && row_ok r e
  | _, _ => false
  end.

Fixpoint remove_matching (e : list string) (rs : list (list NullValues.value)) : option (list (list NullValues.value)) :=
  match rs with
  | nil => None
  | r :: rs => if row_ok r e then Some rs 
               else match remove_matching e rs with Some rs' => Some (r :: rs') | None => None end
  end.

Fixpoint match_unordered (rs : list (list NullValues.value)) (es : list (list string)) : bool :=
  match es with
  | nil => match rs with nil => true | _ => false end
  | e :: es => match remove_matching e rs with Some rs' => match_unordered rs' es | None => false end
  end.

Fixpoint match_ordered (rs : list (list NullValues.value)) (es : list (list string)) : bool :=
  match rs, es with
  | nil, nil => true
  | r :: rs, e :: es => row_ok r e && match_ordered rs es
  | _, _ => false
  end.

Definition out_attr (i : nat) : attribute TNull := Attr_Z ("c" ++ NullValues.string_of_Z (Z.of_nat i)).

(** The value as the client of the dialect shows it: a double of PostgreSQL is printed by [float8out] ([pg_text]:
    [NaN], [Infinity], the exponents [e+20]), the others as the MySQL family prints them ([text_of]). *)
Definition client_value (d : vsem) (v : NullValues.value) : NullValues.value :=
  match v with
  | NullValues.Value_F (Some (x, k)) =>
    if String.eqb (vs_name d) "PostgreSQL"
    then NullValues.Value_string
           (Some (IEEE.pg_text (NullValues.fmt_of (Nat.odd k)) (IEEE.special_of_tag (Nat.div (Nat.modulo k 10) 2)) x))
    else v
  | _ => v
  end.

Definition run_rows (d : vsem) (c : spec_case) (ncols : nat) : list (list NullValues.value) :=
  let db := build_db (sc_tables c) in
  map (fun t => map (fun i => client_value d (dot (TD d) t (out_attr i))) (seq 0 ncols))
      (eval_query_list ORN (dialect_of d) (_basesort _ db) (_instance _ db) (to_dialect d (sc_query c))).

(** the expected rows [e] are rows of [rs], each a different one *)
Fixpoint sub_bag (rs : list (list NullValues.value)) (e : list (list string)) : bool :=
  match e with
  | nil => true
  | x :: e' => match remove_matching x rs with Some rs' => sub_bag rs' e' | None => false end
  end.

(** The allowed orders of an ordered query ([allowed_ordered] of [SqlFull.v]): the expected rows are the
    groups of peers in their order, the rows of a group in any order; with a [LIMIT], the last group may
    be taken in part. *)
Fixpoint groups_ok (gs : list (list (list NullValues.value))) (e : list (list string)) : bool :=
  match gs with
  | nil => match e with nil => true | _ => false end
  | g :: gs' =>
    let k := Nat.min (List.length g) (List.length e) in
    sub_bag g (firstn k e) &&
    (if Nat.ltb k (List.length g) then Nat.eqb (List.length e) k else groups_ok gs' (skipn k e))
  end.

Definition ties_ok (d : vsem) (c : spec_case) (ncols : nat) : bool :=
  let db := build_db (sc_tables c) in
  match order_groups ORN (dialect_of d) (_basesort _ db) (_instance _ db) (to_dialect d (sc_query c)) with
  | Some (gs, lim) =>
    let vgs := map (map (fun t => map (fun i => client_value d (dot (TD d) t (out_attr i))) (seq 0 ncols))) gs in
    let total := List.length (List.concat vgs) in
    let n := match lim with Some n => Nat.min (N.to_nat n) total | None => total end in
    Nat.eqb (List.length (sc_expected c)) n && groups_ok vgs (sc_expected c)
  | None => false
  end.

(** the query is not accepted by the dialect (an unknown function, a wrong number of arguments, a construct which
    it does not have), or its evaluation fails *)
Definition error_ok (d : vsem) (c : spec_case) : bool :=
  let db := build_db (sc_tables c) in
  let q := to_dialect d (sc_query c) in
  negb (accepted_by (dialect_of d) (vs_supports d) q) ||
  match eval_query_result ORN (dialect_of d) (_basesort _ db) (_instance _ db) q with
  | QR_Error _ => true
  | QR_Rows _ _ => false
  end.

Definition check_case (d : vsem) (c : spec_case) : bool :=
  if sc_error c then error_ok d c else
  let ncols := match sc_expected c with e :: _ => List.length e | nil => 0%nat end in
  match sc_limit c with
  | Some n =>
    (* any [n] rows of the result *)
    let rs := run_rows d c (match ncols with O => 1 | _ => ncols end) in
    Nat.eqb (List.length (sc_expected c)) (Nat.min n (List.length rs)) && sub_bag rs (sc_expected c)
  | None =>
    match sc_expected c with
    | nil => Nat.eqb (List.length (run_rows d c 1)) 0%nat
    | _ => if sc_ordered c
           then match_ordered (run_rows d c ncols) (sc_expected c) || ties_ok d c ncols
           else match_unordered (run_rows d c ncols) (sc_expected c)
    end
  end.

Definition failures (d : vsem) (cs : list spec_case) : list string :=
  map sc_id (filter (fun c => negb (check_case d c)) cs).

(** The text of a value, for the diagnosis of a failure *)
Definition show_value (v : NullValues.value) : string :=
  if NullValues.is_err v then "ERROR"
  else if NullValues.is_null v then "NULL"
  else match text_of v with Some s => s | None => "?" end.

Definition show_actual (d : vsem) (c : spec_case) : list (list string) :=
  let ncols := match sc_expected c with e :: _ => List.length e | nil => 1%nat end in
  map (map show_value) (run_rows d c ncols).

Definition join_strings (sep : string) (l : list string) : string :=
  match l with nil => "" | x :: l => fold_left (fun acc y => acc ++ sep ++ y) l x end.

Definition show_rows (rows : list (list string)) : string :=
  let n := List.length rows in
  "[" ++ join_strings " / " (map (join_strings ",") (firstn 4 rows)) ++ (if Nat.ltb 4 n then " ... (" ++ NullValues.string_of_Z (Z.of_nat n) ++ " rows)" else "") ++ "]".

(** For each failing case: its identifier, the statement, the expected rows and the actual ones. *)
Definition diagnose (d : vsem) (cs : list spec_case) : list string :=
  map (fun c => sc_id c ++ " | " ++ sc_sql c ++ " | expected " ++
                (if sc_error c then "an error" else show_rows (sc_expected c)) ++ " | got " ++ show_rows (show_actual d c))
      (filter (fun c => negb (check_case d c)) cs).
