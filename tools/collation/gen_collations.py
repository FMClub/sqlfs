#!/usr/bin/env python3
"""Generate src/data/dialects/CollationData.v from the collation tables of the engines.

  gen_collations.py MARIADB_SERVER MYSQL_SERVER > src/data/dialects/CollationData.v

- utf8mb4_general_ci: weight_general_ci_page00..05 of MariaDB strings/ctype-unicode300-general_ci.h
  (the same table as MySQL's): the weight of a character is a code point (its upper case, without accent).
- utf8mb4_0900_ai_ci: the primary weights of UCA 9.0.0 in MySQL strings/uca900_data.h: for a page p,
  page[c] is the number of collation elements of the character c, and page[256 + j * 768 + c] is the
  primary weight of its j-th element (0 for an ignorable element).
- utf8mb4_unicode_520_ci: uca520_p000..002 of MariaDB strings/ctype-uca.c (fixed number of weights per
  character in each page, 0 for none); utf8mb4_unicode_ci: page000data..page002data (UCA 4.0.0), same format.
Only the code points below 0x300 (Latin, the IPA extensions and the spacing modifiers) are generated;
the other characters are compared by their code point (documented in CollationData.v).
"""
import re
import sys

MAXCP = 0x300


def c_array(text, name):
    m = re.search(r'%s\[\d*\]\s*=\s*\{(.*?)\};' % re.escape(name), text, re.S)
    if not m:
        raise SystemExit('no array ' + name)
    body = re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S)
    return [int(x, 0) for x in re.findall(r'0x[0-9A-Fa-f]+|\d+', body)]


def general_ci(maria):
    text = open(maria + '/strings/ctype-unicode300-general_ci.h').read()
    w = []
    for p in range(MAXCP >> 8):
        w += c_array(text, 'weight_general_ci_page%02X' % p)
    return w[:MAXCP]


def uca900(mysql):
    text = open(mysql + '/strings/uca900_data.h').read()
    res = []
    for p in range(MAXCP >> 8):
        page = c_array(text, 'uca900_p%03X' % p)
        for c in range(256):
            n = page[c]
            res.append([page[256 + j * 768 + c] for j in range(n) if page[256 + j * 768 + c] != 0])
    return res


def uca520(maria, prefix='uca520_p%03X'):
    text = open(maria + '/strings/ctype-uca.c').read()
    res = []
    for p in range(MAXCP >> 8):
        name = prefix % p
        m = re.search(r'%s\[\]\s*=\s*\{\s*/\*[^*]*\((\d+) weights per char\)' % re.escape(name), text)
        k = int(m.group(1))
        page = c_array(text, name)
        for c in range(256):
            res.append([x for x in page[c * k:(c + 1) * k] if x != 0])
    return res


def coq_list(xs, f):
    out, line = [], ''
    for x in xs:
        s = f(x)
        if len(line) + len(s) > 100:
            out.append(line)
            line = ''
        line += s + '; '
    out.append(line)
    return '[' + '\n   '.join(out).rstrip('; ') + ']'


def main():
    maria, mysql = sys.argv[1], sys.argv[2]
    g = general_ci(maria)
    u9 = uca900(mysql)
    u5 = uca520(maria)
    u4 = uca520(maria, 'page%03Xdata')
    print('''(************************************************************************************)
(**                                                                                 *)
(**                 The Extension of SQLFormalSemantics Library                     *)
(**                                                                                 *)
(**   Collation weights, generated by tools/collation/gen_collations.py from the    *)
(**   tables of MariaDB (strings/ctype-unicode300-general_ci.h, strings/ctype-uca.c) *)
(**   and MySQL (strings/uca900_data.h), for the code points below U+0300.          *)
(**                                                                                 *)
(************************************************************************************)

Require Import List ZArith.
Import ListNotations.
Open Scope Z_scope.

(** [utf8mb4_general_ci]: the weight of the code point [c < 0x300] is [nth c general_ci_weights c] *)
Definition general_ci_weights : list Z :=
  %s.

(** [utf8mb4_0900_ai_ci] (UCA 9.0.0): the primary weights of the code point [c < 0x300] *)
Definition uca900_primary : list (list Z) :=
  %s.

(** [utf8mb4_unicode_520_ci] (UCA 5.2.0): the primary weights of the code point [c < 0x300] *)
Definition uca520_primary : list (list Z) :=
  %s.

(** [utf8mb4_unicode_ci] (UCA 4.0.0): the primary weights of the code point [c < 0x300] *)
Definition uca400_primary : list (list Z) :=
  %s.

Definition uca400_rep : list Z :=
  %s.

(** the least code point with the same primary weights, for [LIKE], which compares characters one by one *)
Definition uca900_rep : list Z :=
  %s.

Definition uca520_rep : list Z :=
  %s.
''' % (coq_list(g, str), coq_list(u9, lambda l: '[' + '; '.join(map(str, l)) + ']'),
       coq_list(u5, lambda l: '[' + '; '.join(map(str, l)) + ']'),
       coq_list(u4, lambda l: '[' + '; '.join(map(str, l)) + ']'), coq_list(reps(u4), str),
       coq_list(reps(u9), str), coq_list(reps(u5), str)))


def reps(table):
    first = {}
    out = []
    for c, w in enumerate(table):
        k = tuple(w)
        if k not in first:
            first[k] = c
        out.append(first[k])
    return out


if __name__ == '__main__':
    main()
