#!/usr/bin/env python3
"""docs/DIALECT_TABLES.md, generated from the model (TODO 7.3).

For every name of the function, predicate and aggregate tables (the names of tools/functions/check_provenance.py)
and every construct of SqlFull.v ([feature]), Coq evaluates which dialects have it (the tables [vs_symb],
[vs_pred], [vs_agg], [vs_table_fun] and [vs_supports] of each dialect record). The tables of docs/DIALECTS.md are
written by hand; this one is computed, so it cannot drift from the model.

Usage: gen_dialect_tables.py   (needs the compiled library in src/)
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools' / 'functions'))
import check_provenance as cp  # noqa: E402

DIALECTS = [('PostgreSQL', 'PostgreSQL'), ('MySQL', 'MySQL'), ('MariaDB', 'MariaDB'), ('TiDB', 'TiDB'),
            ('Percona', 'Percona'), ('PolarDB', 'PolarDB'), ('SQLite', 'SQLite'),
            ('OceanBase MySQL', 'OceanBaseMySQL'), ('OceanBase Oracle', 'OceanBaseOracle')]
FEATURES = re.findall(r'\| (F_[A-Za-z_]+)', re.search(r'Inductive feature : Type :=(.*?)\.\n',
                      (ROOT / 'src/data/sql/SqlFull.v').read_text(), re.S).group(1))


def main():
    names = set()
    for src in cp.SOURCES:
        names |= cp.names_in(src)
    names = sorted(n for n in names if '"' not in n and '\\' not in n)
    lits = '; '.join('"%s"' % n for n in names)
    fnames = ' | '.join('%s => "%s"' % (f, f) for f in FEATURES)
    coq = '''Require Import List String.
Require Import SqlFull Values Dialects PostgreSQL MySQL SQLite OceanBase MariaDB TiDB Percona PolarDB.
Import ListNotations. Open Scope string_scope.
Definition some {A} (o : option A) := match o with Some _ => true | None => false end.
Definition known (d : vsem) (n : string) : bool :=
  some (vs_symb d n) || some (vs_agg d n) || some (vs_pred d n) || some (vs_table_fun d n).
Definition fname (f : feature) : string := match f with %s end.
Definition names := [%s].
Definition feats := [%s].
''' % (fnames, lits, '; '.join(FEATURES))
    for _, v in DIALECTS:
        coq += 'Eval vm_compute in ("%s", List.filter (known %s) names, List.map fname (List.filter (vs_supports %s) feats)).\n' % (v, v, v)
    with tempfile.TemporaryDirectory() as d:
        f = Path(d) / 'Tables.v'
        f.write_text(coq)
        out = subprocess.run(['coqc', '-R', '.', 'SQLFS', str(f)], cwd=ROOT / 'src', capture_output=True,
                             text=True).stdout
    blocks = re.findall(r'= \("([A-Za-z]+)",\s*(\[.*?\]),\s*(\[.*?\])\)', out, re.S)
    has, sup = {}, {}
    for v, ns, fs in blocks:
        has[v] = set(re.findall(r'"([^"]*)"', ns))
        sup[v] = set(re.findall(r'"([^"]*)"', fs))
    if len(blocks) != len(DIALECTS):
        sys.exit('coq output not understood:\n' + out[:2000])
    cols = [v for _, v in DIALECTS]
    head = '| %s | ' + ' | '.join(l for l, _ in DIALECTS) + ' |'
    sep = '|---|' + '---|' * len(DIALECTS)
    lines = ['# The dialects, computed from the model', '',
             'Generated by `tools/docs/gen_dialect_tables.py`: Coq evaluates the tables of each dialect record '
             '(`src/data/dialects/`). `x` means that the dialect has the name or accepts the construct. The sources '
             'of each behaviour are in `docs/functions/*.md` and `docs/closeouts/*.md`.', '',
             '## Constructs (`supports`)', '', head % 'Construct', sep]
    for f in FEATURES:
        lines.append('| `%s` | ' % f + ' | '.join('x' if f in sup[v] else '' for v in cols) + ' |')
    lines += ['', '## Functions, predicates, aggregates and table functions', '', head % 'Name', sep]
    for n in names:
        row = ['x' if n in has[v] else '' for v in cols]
        if any(row):
            lines.append('| `%s` | ' % n.replace('|', '\\|') + ' | '.join(row) + ' |')
    lines.append('')
    lines.append('%d names, %d constructs.' % (len(names), len(FEATURES)))
    (ROOT / 'docs' / 'DIALECT_TABLES.md').write_text('\n'.join(lines) + '\n')
    print('%d names, %d constructs' % (len(names), len(FEATURES)))


if __name__ == '__main__':
    main()
