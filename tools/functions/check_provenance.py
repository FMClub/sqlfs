#!/usr/bin/env python3
"""Provenance of the function tables (TODO 2.11).

Every name of the tables of functions, predicates and aggregates of the dialects (the entries
`("name", ...)` of the Coq sources) must be described in one of the tables of `docs/functions/*.md`,
whose rows give the sources (the engines' files or manual pages). The script lists the names of
each file of code, looks for each one in the documentation (as `name` between backquotes, or as the
name of a row), writes `docs/functions/INDEX.md` (every name, the files of code which define it, the
document which describes it) and exits with an error if a name is not documented.

Usage: check_provenance.py [--write]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCES = [
    'src/data/proof_of_concept/Values.v',
    'src/data/dialects/ValueKit.v',
    'src/data/dialects/PostgreSQL.v',
    'src/data/dialects/MySQL.v',
    'src/data/dialects/SQLite.v',
    'src/data/dialects/OceanBase.v',
    'src/data/dialects/StringFuns.v',
    'src/data/dialects/RegexFuns.v',
    'src/data/dialects/Aggregates.v',
    'src/data/dialects/TemporalFuns.v',
    'src/data/dialects/JsonFuns.v',
    'src/data/dialects/SystemFuns.v',
]
ENTRY = re.compile(r'\(\s*"([^"\n]{1,40})"\s*,')
# names generated by a function in the code (not written as literals)
GENERATED = {
    'StringFuns.v': ['like_escape', 'not like_escape', 'ilike', 'not ilike', 'ilike_escape', 'not ilike_escape'],
}


def names_in(path):
    text = (ROOT / path).read_text(encoding='utf-8')
    # the comments are removed (they quote names which are not entries)
    text = re.sub(r'\(\*.*?\*\)', '', text, flags=re.S)
    found = set(ENTRY.findall(text))
    found |= set(GENERATED.get(Path(path).name, []))
    return found


def documented():
    docs = {}
    for md in sorted((ROOT / 'docs/functions').glob('*.md')):
        if md.name == 'INDEX.md':
            continue
        text = md.read_text(encoding='utf-8')
        for tok in re.findall(r'`([^`\n]+)`', text):
            tok = tok.replace('\\|', '|')
            for part in re.split(r'[\s,/()\[\]|…]+', tok):
                part = part.strip().lower()
                if part:
                    docs.setdefault(part, md.name)
            docs.setdefault(tok.strip().lower(), md.name)
    return docs


def main():
    write = '--write' in sys.argv
    docs = documented()
    where = {}
    for src in SOURCES:
        for n in names_in(src):
            where.setdefault(n, set()).add(Path(src).name)
    missing = sorted(n for n in where if n.lower() not in docs)
    lines = ['# Index of the function tables (generated by `tools/functions/check_provenance.py`)', '',
             'Every name of the tables of functions, predicates and aggregates, the files which define it, '
             'and the document which describes it with its sources.', '',
             '| Name | Defined in | Described in |', '|---|---|---|']
    for n in sorted(where):
        lines.append('| `%s` | %s | %s |' % (n.replace('|', '\\|'), ', '.join(sorted(where[n])),
                                          docs.get(n.lower(), '**missing**')))
    if write:
        (ROOT / 'docs/functions/INDEX.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('%d names, %d undocumented' % (len(where), len(missing)))
    for n in missing:
        print('  missing:', n, '(' + ', '.join(sorted(where[n])) + ')')
    return 1 if missing else 0


if __name__ == '__main__':
    sys.exit(main())
